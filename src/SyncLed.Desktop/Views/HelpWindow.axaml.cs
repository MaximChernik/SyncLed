using Avalonia;
using Avalonia.Controls;
using Avalonia.Input;
using Avalonia.Interactivity;
using Avalonia.Media;

namespace SyncLed.Avalonia.Views;

/// <summary>Справка по общим параметрам и параметрам ленты.</summary>
public sealed partial class HelpWindow : Window
{
    private static readonly IBrush TextBrush = new SolidColorBrush(Color.Parse("#F4F7FC"));
    private static readonly IBrush MutedBrush = new SolidColorBrush(Color.Parse("#8490A4"));
    private static readonly IBrush DividerBrush = new SolidColorBrush(Color.Parse("#1E2634"));

    public HelpWindow()
    {
        InitializeComponent();
        FillHelp();
        Opened += (_, _) => HelpScroller.Offset = new Vector(0, 0);
    }

    public new void Show(Window? owner = null)
    {
        if (owner != null)
        {
            Owner = owner;
            WindowStartupLocation = WindowStartupLocation.CenterOwner;
        }
        base.Show();
        Activate();
    }

    private void OnCloseClick(object? sender, RoutedEventArgs e) => Close();

    private void OnWindowKeyDown(object? sender, KeyEventArgs e)
    {
        if (e.Key == Key.Escape)
        {
            e.Handled = true;
            Close();
        }
        else if (e.Key == Key.Enter)
        {
            e.Handled = true;
            Close();
        }
    }

    private void AddSection(string title)
    {
        var row = new StackPanel { Margin = new Thickness(0, 18, 0, 8), Spacing = 7 };
        var heading = new TextBlock
        {
            Text = title.ToUpperInvariant(),
            FontSize = 11,
            FontWeight = FontWeight.Bold,
            Foreground = TextBrush
        };
        row.Children.Add(heading);
        row.Children.Add(new Border
        {
            Height = 1,
            Background = DividerBrush
        });
        HelpStack.Children.Add(row);
    }

    private void Add(string title, string text)
    {
        var item = new StackPanel { Margin = new Thickness(0, 11, 0, 0), Spacing = 3 };
        item.Children.Add(new TextBlock
        {
            Text = title,
            FontSize = 12.5,
            FontWeight = FontWeight.SemiBold,
            Foreground = TextBrush
        });
        item.Children.Add(new TextBlock
        {
            Text = text,
            FontSize = 12,
            Foreground = MutedBrush,
            TextWrapping = TextWrapping.Wrap
        });
        HelpStack.Children.Add(item);
    }

    private void FillHelp()
    {
        AddSection("Общие настройки");

        Add("Частота обновления",
            "Сколько раз в секунду программа считывает экран и отправляет цвета на ленты. " +
            "Выше — плавнее реакция на видео и игры, но больше нагрузка на процессор и USB. " +
            "Для статичной работы достаточно 10–15 FPS, для игр и фильмов — 30–60.");

        Add("Яркость",
            "Общая программная яркость всех лент (5–100 %). Уменьшайте вечером, чтобы подсветка " +
            "не слепила. Очень низкие значения могут «съедать» тёмные оттенки.");

        Add("Насыщенность",
            "0 % — чёрно-белая подсветка, 100 % — как на экране, до 200 % — цвета более сочные. " +
            "Помогает, если лента выглядит бледнее монитора.");

        Add("Гамма",
            "Коррекция средних тонов (50–250 %). Ниже 100 % делает полутени темнее, выше — светлее, " +
            "не обрезая белый. Удобно для согласования яркости разных лент.");

        Add("Сглаживание",
            "Смягчает резкие перепады цвета между кадрами (0–95 %). Больше — спокойнее и меньше " +
            "мерцания, но заметнее запаздывание при быстрой смене картинки.");

        Add("Порог чёрного",
            "Всё, что темнее порога (0–60), считается чёрным. Убирает слабое свечение в тёмных " +
            "сценах и шум чёрных полос по краям экрана.");

        Add("Глубина краёв",
            "Насколько глубоко внутрь экрана заходит зона выборки цвета (4–30 %). Больше — цвет " +
            "усредняется с большей области и меньше зависит от мелких деталей у края.");

        Add("Яркость Bluetooth-лент (общая)",
            "Аппаратная яркость BLE-контроллеров (1–100). Применяется к лентам, у которых не задано " +
            "своё значение; на USB-ленты не влияет. Слишком высокое значение может упереться " +
            "в питание USB-порта — тогда контроллер уходит в защиту.");

        Add("Запускать синхронизацию при запуске",
            "Сразу включать захват экрана после старта программы.");

        Add("Запускать вместе с Windows",
            "Добавляет приложение в автозагрузку текущего пользователя.");

        Add("Сворачивать в трей",
            "Кнопка закрытия прячет окно в трей, не завершая программу; двойной щелчок по значку " +
            "возвращает окно. Если выключено, крестик полностью закрывает приложение.");

        Add("Искать LED-устройства других производителей",
            "Дополнительно проверять vendor-defined HID-устройства совместимых контроллеров. " +
            "Поиск идёт дольше, но так находятся небрендовые ленты.");

        Add("Искать Bluetooth-ленты",
            "Сканировать BLE-устройства. Если Bluetooth-лент нет, отключите — поиск станет быстрее.");

        AddSection("Параметры ленты");

        Add("Режим",
            "Синхронизация с экраном, свой цвет, выключено или наследование от группы и общих настроек.");

        Add("Отдельные настройки",
            "В окне настроек ленты. Пока он выключен, лента использует значения группы " +
            "(если она выбрана) или общие настройки. Включите, чтобы задать свои яркость, " +
            "насыщенность, гамму, сглаживание, порог чёрного и глубину краёв.");

        Add("Яркость контроллера (BLE)",
            "Аппаратная яркость конкретной Bluetooth-ленты (1–100). Пока значение не задано, " +
            "используется общая яркость BLE-лент.");

        Add("Количество ламп",
            "Сколько светодиодов в ленте. Нужно для равномерного распределения цветов по всей длине: " +
            "при неверном значении градиент будет сжат или растянут.");

        Add("Сдвиг начала",
            "Смещает начало цветовой картины вдоль ленты, чтобы стык на углу монитора был незаметен.");

        Add("LED по горизонтали",
            "Сколько светодиодов отдаётся верхней и нижней сторонам монитора. Значение 0 рассчитывает " +
            "число автоматически по пропорциям экрана.");

        Add("Реверс",
            "Меняет направление ленты, если она физически установлена наоборот.");

        Add("Усиление R, G, B",
            "Поканальная калибровка: компенсирует разный оттенок светодиодов. Например, если белый " +
            "уходит в зелень, уменьшите усиление G.");

        Add("Группа",
            "Лента использует настройки, режим и цвет выбранной группы. Участники группы меняются " +
            "синхронно.");

        Add("Монитор",
            "К какому монитору привязана лента и по какому краю идёт подсветка.");

        AddSection("Прочее");

        Add("Миниатюра ленты",
            "Показывает текущие цвета по периметру монитора. Пунктирная рамка отмечает область, " +
            "которая попадает в подсветку.");

        Add("Горячая клавиша Ctrl+Alt+L",
            "Включает или выключает синхронизацию из любого приложения.");

        Add("Кнопки проверки ленты",
            "Показывают тестовые цвета, бегущий огонёк или вспышки — удобно проверить порядок ламп, " +
            "реверс и сдвиг.");
    }
}
